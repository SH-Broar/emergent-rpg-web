import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { createPinia, setActivePinia } from 'pinia';

const root = fileURLToPath(new URL('../', import.meta.url));
const saved = new Map();
const original = { window: globalThis.window, localStorage: globalThis.localStorage, fetch: globalThis.fetch };
globalThis.window = { setTimeout: () => 0 };
globalThis.localStorage = { getItem: key => saved.get(key) ?? null, setItem: (key, value) => saved.set(key, value), removeItem: key => saved.delete(key) };
const server = await createServer({ root, server: { middlewareMode: true }, appType: 'custom' });
try {
  setActivePinia(createPinia());
  const { useRunStore } = await server.ssrLoadModule('/src/stores/run.ts');
  const { useDataStore } = await server.ssrLoadModule('/src/stores/data.ts');
  const { useMetaStore } = await server.ssrLoadModule('/src/stores/meta.ts');
  const { loadAllData } = await server.ssrLoadModule('/src/data/loader.ts');
  const chaos = await server.ssrLoadModule('/src/systems/chaos.ts');
  const fieldChaos = await server.ssrLoadModule('/src/systems/field-chaos.ts');
  const field = await server.ssrLoadModule('/src/systems/field-simulation.ts');
  const generation = await server.ssrLoadModule('/src/systems/field-generation.ts');
  const combat = await server.ssrLoadModule('/src/systems/field-combat.ts');
  globalThis.fetch = async url => new Response(readFileSync(join(root, 'public', String(url).replace(/^\//, '')), 'utf8'));
  const data = useDataStore(); data.data = await loadAllData('/');
  const meta = useMetaStore(), run = useRunStore(), id = fieldChaos.FRACTURED_TIME_CHAOS_ID;
  const timeline = [...data.timelines.values()].find(t => data.nodeMaps.get(t.nodeMapId)?.nodes.some(n => n.id === 'n-iluneon-square'));
  const definition = data.chaosDefs.get(id);
  assert.ok(definition);
  assert.equal(chaos.chaosLevelSummary(definition, 1), '적 체력 +40% · 공격 +25%');
  const active = [{ id, intensity: 1 }];
  meta.storyEndings = { seen: [], chaosUnlocked: false };
  meta.chaosTierRevealed = 4; meta.soulResource = 100;
  assert(!fieldChaos.isFracturedTimeUnlocked(meta));
  assert(!chaos.shopChaos().some(c => c.id === id));
  assert(!chaos.purchaseChaos(id)); assert.equal(meta.soulResource, 100);
  function start(selected = []) {
    run.startRun({ timelineId: timeline.id, raceId: 'human', season: 'spring', startNodeId: 'n-iluneon-square', maxHp: 1000, maxMp: 3, timeLimit: 300, activeChaos: selected });
    const a = field.ensureField(run.data);
    a.world.entities = { player: a.player };
    a.space.width = 11; a.space.height = 11; a.space.tiles = Array.from({ length: 11 }, () => Array(11).fill('grass'));
    a.space.exits = []; a.player.pos = { x: 5, y: 5 }; a.player.colors = {};
    a.player.properties.hardness = 0; a.player.properties.guard = 0;
    return a;
  }
  start(active);
  assert(!fieldChaos.hasFracturedTime(run.data), 'an injected but unearned story Chaos is discarded at run start');
  assert.equal(run.data.chaosScore, 0);
  meta.storyEndings = { seen: ['dun'], chaosUnlocked: true };
  assert(fieldChaos.isFracturedTimeUnlocked(meta));
  assert(!chaos.purchaseChaos(id)); assert.equal(meta.soulResource, 100);
  let a = start(active);
  assert(fieldChaos.hasFracturedTime(run.data));
  assert.equal(run.data.chaosScore, 6);
  assert.equal(fieldChaos.fieldChaosHpMultiplier(run.data, 'boss'), 1.4);
  assert.equal(fieldChaos.fieldChaosAttackMultiplier(run.data, 'boss'), 1.25);
  assert.equal(run.data.maxMp, 3);
  const mix = { activeChaos: [...active, { id: 'ch-enemy-hp', intensity: 2 }, { id: 'ch-elite-hp', intensity: 1 }, { id: 'ch-enemy-atk', intensity: 2 }, { id: 'ch-boss-atk', intensity: 1 }, { id: 'ch-enemy-def', intensity: 2 }] };
  assert(Math.abs(fieldChaos.fieldChaosHpMultiplier(mix, 'normal') - 1.6) < 1e-9);
  assert(Math.abs(fieldChaos.fieldChaosHpMultiplier(mix, 'elite') - 1.75) < 1e-9);
  assert(Math.abs(fieldChaos.fieldChaosAttackMultiplier(mix, 'normal') - 1.45) < 1e-9);
  assert(Math.abs(fieldChaos.fieldChaosAttackMultiplier(mix, 'boss') - 1.6) < 1e-9);
  assert.equal(fieldChaos.fieldChaosDefenseBonus(mix), 4);
  assert.equal(fieldChaos.fieldChaosHpMultiplier({ activeChaos: [...active, ...active] }, 'boss'), 1.4, 'duplicate entries never double the challenge');
  console.log('PASS earned unlock, free selection gate, blocked purchase, start normalization and rank-specific stacked effects');

  const boss = data.bosses.get('bs-arc-dun');
  assert.ok(boss);
  function prepare(selected) {
    const a = start(selected);
    const enemy = generation.spawnCreature(run.data, a.world, a.space, boss, 0, 'boss');
    enemy.pos = { x: 5, y: 4 };
    const attack = combat.planAttack(a.world, enemy, a.player);
    assert(attack?.cells.some(c => c.pos.x === a.player.pos.x && c.pos.y === a.player.pos.y));
    return { ...a, enemy, attack };
  }
  const normal = prepare([]), normalHp = normal.enemy.creature.maxHp, normalDamage = normal.attack.damage;
  const hard = prepare(active);
  assert.equal(hard.enemy.creature.maxHp, Math.ceil(normalHp * 1.4));
  assert.equal(hard.attack.damage, Math.ceil(normalDamage * 1.25));
  assert.equal(hard.attack.name, normal.attack.name);
  assert.deepEqual(hard.attack.cells, normal.attack.cells);
  assert.equal(hard.attack.castTurns, normal.attack.castTurns);
  const cell = hard.attack.cells.find(c => c.pos.x === hard.player.pos.x && c.pos.y === hard.player.pos.y);
  const before = hard.player.properties.integrity;
  hard.enemy.creature.pending = hard.attack;
  combat.resolveAttack(hard.world, hard.enemy);
  const lost = Math.round((before - hard.player.properties.integrity) * hard.player.properties.maxHp / 100);
  assert.equal(lost, Math.floor(hard.attack.damage * cell.multiplier));
  const hp = hard.enemy.creature.maxHp;
  run.saveActiveRun(); run.$reset(); assert(run.loadActiveRun());
  const loaded = field.ensureField(run.data);
  assert.equal(loaded.world.entities[hard.enemy.id].creature.maxHp, hp, 'loading does not multiply enemy HP again');
  assert(fieldChaos.hasFracturedTime(run.data));
  console.log('PASS actual Dun spawn HP, visible telegraph, resolved hit damage, unchanged timing and save/load without duplicate scaling');
  const guarded = prepare([{ id: 'ch-enemy-def', intensity: 2 }, { id: 'ch-enemy-hp', intensity: 2 }]);
  assert.equal(guarded.enemy.properties.guard, 4);
  combat.hit(guarded.world, guarded.player, guarded.enemy, 40);
  assert.equal(guarded.enemy.properties.guard, 0);
  field.ensureField(run.data);
  assert.equal(guarded.enemy.properties.guard, 0, 'initial guard is not restored by rendering or reentry');
  guarded.enemy.creature.balanceVersion = 1;
  guarded.enemy.creature.maxHp = normalHp;
  guarded.enemy.properties.maxHp = normalHp;
  guarded.enemy.properties.integrity = 63;
  field.ensureField(run.data);
  assert.equal(guarded.enemy.creature.maxHp, Math.ceil(normalHp * 1.2));
  assert.equal(guarded.enemy.properties.integrity, 63, 'an old creature keeps its health fraction during migration');
  guarded.enemy.creature.balanceVersion = 1; guarded.enemy.properties.integrity = 0;
  field.ensureField(run.data);
  assert.equal(guarded.enemy.properties.integrity, 0, 'migration never resurrects a defeated creature');
  console.log('PASS one-time starting guard, old-save HP fraction migration and no resurrection');
} finally {
  globalThis.window = original.window; globalThis.localStorage = original.localStorage; globalThis.fetch = original.fetch;
  await server.close();
}
